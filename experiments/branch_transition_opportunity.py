"""Audit independent raw-molecule support across reduced-graph branches.

All sequence coordinates are 0-based and intervals are half-open. Synthetic
origins are generated by the fixture but never used by this audit.
"""
import argparse
import hashlib
import inspect
import json
from collections import Counter, defaultdict
from pathlib import Path

from anvaya.damage_string_graph import assemble
from anvaya.overlap_assembly import _n50
from anvaya.raw_consensus import DamageProfile
from anvaya.sequences import reverse_complement

from variable_length_validation import _case_identities, fixture


SEED = 199001
CASES = (("clean_unique", 0.0, 20.0), ("damage_unique", 0.25, 10.0))
ANCHOR_K = 15


def _oriented(read, reverse):
    return reverse_complement(read.sequence) if reverse else read.sequence


def _spell_transition(contigs, incoming, outgoing):
    """Spell source-centre-target and return sequence plus centre interval."""
    source = _oriented(contigs[incoming.source[0]], incoming.source[1])
    centre = _oriented(contigs[incoming.target[0]], incoming.target[1])
    target = _oriented(contigs[outgoing.target[0]], outgoing.target[1])
    if incoming.target != outgoing.source:
        raise ValueError("transition edges do not share an oriented node")
    sequence = list(source)
    for position, base in incoming.corrections:
        sequence[position] = base
    centre_start = incoming.shift
    if centre_start != len(sequence) - incoming.overlap:
        raise ValueError("incoming edge coordinates are inconsistent")
    sequence.extend(centre[incoming.overlap:])
    for position, base in outgoing.corrections:
        sequence[centre_start + position] = base
    target_start = centre_start + outgoing.shift
    if target_start != len(sequence) - outgoing.overlap:
        raise ValueError("outgoing edge coordinates are inconsistent")
    sequence.extend(target[outgoing.overlap:])
    return "".join(sequence), centre_start, centre_start + len(centre)


def _compatible(read, reverse, sequence, offset, profile):
    observed = _oriented(read, reverse)
    if offset < 0 or offset + len(observed) > len(sequence):
        return False
    for oriented_position, observed_base in enumerate(observed):
        latent = sequence[offset + oriented_position]
        if observed_base == latent:
            continue
        raw_position = (
            len(read.sequence) - 1 - oriented_position
            if reverse else oriented_position
        )
        if read.qualities is None or read.qualities[raw_position] < 20:
            return False
        raw_latent = reverse_complement(latent) if reverse else latent
        raw_observed = read.sequence[raw_position]
        rate = 0.0
        if raw_latent == "C" and raw_observed == "T":
            if raw_position < len(profile.five_prime_ct):
                rate = profile.five_prime_ct[raw_position]
        elif raw_latent == "G" and raw_observed == "A":
            distance_3p = len(read.sequence) - 1 - raw_position
            if distance_3p < len(profile.three_prime_ga):
                rate = profile.three_prime_ga[distance_3p]
        if rate <= 0.0:
            return False
    return True


def _transition_key(incoming, outgoing):
    forward = (incoming.source, incoming.target, outgoing.target)
    reverse = tuple((index, not orientation) for index, orientation in reversed(forward))
    return min(forward, reverse)


def _raw_anchor_index(reads, anchors_per_read=None):
    index = defaultdict(list)
    for read_index, read in enumerate(reads):
        for reverse in (False, True):
            sequence = _oriented(read, reverse)
            positions = list(range(len(sequence) - ANCHOR_K + 1))
            if anchors_per_read is not None and len(positions) > anchors_per_read:
                positions = sorted({
                    round(i * (len(positions) - 1) / (anchors_per_read - 1))
                    for i in range(anchors_per_read)
                })
            for position in positions:
                index[sequence[position:position + ANCHOR_K]].append(
                    (read_index, reverse, position)
                )
    return index


def _all_placements(sequence, reads, profile, anchor_index):
    candidates = set()
    for path_position in range(len(sequence) - ANCHOR_K + 1):
        anchor = sequence[path_position:path_position + ANCHOR_K]
        for read_index, reverse, read_position in anchor_index.get(anchor, ()):
            offset = path_position - read_position
            candidates.add((read_index, reverse, offset))
    return {
        placement for placement in candidates
        if _compatible(
            reads[placement[0]], placement[1], sequence, placement[2], profile,
        )
    }


def _placements(sequence, centre_start, centre_end, reads, profile, anchor_index):
    return {
        placement for placement in _all_placements(
            sequence, reads, profile, anchor_index,
        )
        if placement[2] < centre_start
        and placement[2] + len(reads[placement[0]].sequence) > centre_end
    }


def _projected_n50(contigs, reduced, excluded, selected):
    """Projection-only N50 with selected transitions and no node reuse."""
    outgoing = defaultdict(list)
    incoming = defaultdict(list)
    for edge in reduced.values():
        outgoing[edge.source].append(edge)
        incoming[edge.target].append(edge)
    reciprocal = {
        (edge.source, edge.target): edge for edge in reduced.values()
        if len(outgoing[edge.source]) == 1 and len(incoming[edge.target]) == 1
    }
    usable = dict(reciprocal)
    for transition in selected:
        first = (transition[0], transition[1])
        second = (transition[1], transition[2])
        if first in reduced and second in reduced:
            usable[first] = reduced[first]
            usable[second] = reduced[second]

    successor = {}
    predecessor = {}
    for first_key, first in usable.items():
        for second_key, second in usable.items():
            if first.target != second.source:
                continue
            transition = _transition_key(first, second)
            regular = (
                len(outgoing[first.target]) == 1
                and len(incoming[first.target]) == 1
            )
            if regular or transition in selected:
                if first_key not in successor and second_key not in predecessor:
                    successor[first_key] = second_key
                    predecessor[second_key] = first_key

    paths = []
    visited = set()
    for start in sorted(key for key in usable if key not in predecessor):
        if start in visited:
            continue
        keys = []
        key = start
        while key in usable and key not in visited:
            visited.add(key)
            keys.append(key)
            key = successor.get(key)
        if keys:
            paths.append(tuple(usable[item] for item in keys))

    candidates = []
    seen_sequences = set()
    for path in paths:
        sequence = list(_oriented(contigs[path[0].source[0]], path[0].source[1]))
        nodes = {path[0].source[0]}
        current = path[0].source
        valid = True
        for edge in path:
            if edge.source != current:
                valid = False
                break
            source = _oriented(contigs[edge.source[0]], edge.source[1])
            source_start = len(sequence) - len(source)
            for position, base in edge.corrections:
                sequence[source_start + position] = base
            target = _oriented(contigs[edge.target[0]], edge.target[1])
            sequence.extend(target[edge.overlap:])
            nodes.add(edge.target[0])
            current = edge.target
        if not valid:
            continue
        spelled = "".join(sequence)
        canonical = min(spelled, reverse_complement(spelled))
        if canonical not in seen_sequences:
            seen_sequences.add(canonical)
            candidates.append((len(spelled), nodes))

    used = set()
    lengths = []
    for length, nodes in sorted(candidates, reverse=True):
        if nodes & used:
            continue
        lengths.append(length)
        used.update(nodes)
    lengths.extend(
        len(contig.sequence) for index, contig in enumerate(contigs)
        if index not in used and index not in excluded
    )
    return _n50(lengths)


def audit_reduced_graph(contigs, reduced, excluded, reads, molecule_ids, profile):
    outgoing = defaultdict(list)
    incoming = defaultdict(list)
    for edge in reduced.values():
        outgoing[edge.source].append(edge)
        incoming[edge.target].append(edge)
    ambiguous = {
        node for node in set(outgoing) | set(incoming)
        if len(outgoing[node]) > 1 or len(incoming[node]) > 1
    }
    canonical_groups = defaultdict(set)
    for read_index, read in enumerate(reads):
        canonical_groups[min(read.sequence, reverse_complement(read.sequence))].add(
            molecule_ids[read_index]
        )
    anchor_index = _raw_anchor_index(reads)
    transitions = {}
    for centre in sorted(ambiguous):
        for first in incoming.get(centre, ()):
            for second in outgoing.get(centre, ()):
                key = _transition_key(first, second)
                if key in transitions:
                    continue
                sequence, centre_start, centre_end = _spell_transition(
                    contigs, first, second,
                )
                endpoint_molecules = set()
                for node in (first.source, centre, second.target):
                    endpoint_molecules.update(
                        canonical_groups[contigs[node[0]].sequence]
                    )
                placements = _placements(
                    sequence, centre_start, centre_end, reads, profile, anchor_index,
                )
                by_molecule = defaultdict(set)
                for placement in placements:
                    molecule = molecule_ids[placement[0]]
                    if molecule not in endpoint_molecules:
                        by_molecule[molecule].add(placement)
                transitions[key] = {
                    molecule for molecule, values in by_molecule.items()
                    if len(values) == 1
                }

    by_branch_molecule = defaultdict(lambda: defaultdict(set))
    for key, molecules in transitions.items():
        branch = key[1][0]
        for molecule in molecules:
            by_branch_molecule[branch][molecule].add(key)
    for branch_molecules in by_branch_molecule.values():
        for molecule, keys in branch_molecules.items():
            if len(keys) > 1:
                for key in keys:
                    transitions[key].discard(molecule)

    selected = set()
    for branch in {key[1][0] for key in transitions}:
        branch_transitions = [key for key in transitions if key[1][0] == branch]
        supported = [key for key in branch_transitions if len(transitions[key]) >= 2]
        if len(supported) == 1 and all(
            not transitions[key] for key in branch_transitions if key != supported[0]
        ):
            selected.add(supported[0])
    affected = {node[0] for key in selected for node in key}
    return {
        "ambiguous_oriented_nodes": len(ambiguous),
        "branch_physical_nodes": len({node[0] for node in ambiguous}),
        "possible_transitions": len(transitions),
        "transitions_with_1_molecule": sum(bool(value) for value in transitions.values()),
        "transitions_with_2_molecules": sum(len(value) >= 2 for value in transitions.values()),
        "uniquely_resolved_transitions": len(selected),
        "affected_physical_nodes": len(affected),
        "projection_baseline_n50": _projected_n50(
            contigs, reduced, excluded, set(),
        ),
        "projection_only_n50": _projected_n50(contigs, reduced, excluded, selected),
        "support_histogram": dict(sorted(Counter(
            len(value) for value in transitions.values()
        ).items())),
    }


def evaluate_case(name, damage, coverage):
    references, reads, origins, events, errors = fixture(
        SEED, "unique", damage, 0.0, include_events=True, coverage=coverage,
    )
    rates = tuple(damage * 0.65 ** position for position in range(5))
    profile = DamageProfile(rates, rates)
    result = {}
    molecule_ids = list(range(len(reads)))

    def capture(contigs, reduced, excluded):
        result.update(audit_reduced_graph(
            contigs, reduced, excluded, reads, molecule_ids, profile,
        ))

    pool, graph = assemble(
        reads, molecule_ids=molecule_ids,
        damage_profile=profile if damage else None,
        reduced_graph_audit=capture,
    )
    lengths = [len(record.current.sequence) for record in pool.active_derived]
    baseline_n50 = _n50(lengths)
    if result["projection_baseline_n50"] != baseline_n50:
        raise ValueError("projection audit does not reproduce baseline N50")
    result.update({
        "seed": SEED,
        "scenario": name,
        "target_coverage": coverage,
        "reads": len(reads),
        "baseline_contigs": len(lengths),
        "baseline_n50": baseline_n50,
        "graph": graph,
        **_case_identities(references, reads, origins, events, errors, profile),
    })
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    arguments = parser.parse_args()
    if arguments.output.exists():
        parser.error("output already exists")
    arguments.output.mkdir(parents=True)
    root = Path(__file__).resolve().parents[1]
    paths = sorted({
        Path(__file__).resolve(), Path(inspect.getfile(fixture)).resolve(),
        Path(inspect.getfile(assemble)).resolve(),
    })
    manifest = {
        "hypothesis": "ambiguous reduced-graph transitions have two independent spanning molecules",
        "rejection_condition": "no transition has at least two independent spanning molecules",
        "coordinate_system": "0-based; intervals half-open",
        "seed": SEED,
        "cases": [list(case) for case in CASES],
        "minimum_independent_molecules": 2,
        "endpoint_molecules_excluded": True,
        "conflicting_pairings_abstain": True,
        "source_sha256": {
            path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in paths
        },
    }
    cases = [evaluate_case(*case) for case in CASES]
    output = {"manifest": manifest, "cases": cases}
    (arguments.output / "branch-transition-opportunity.json").write_text(
        json.dumps(output, indent=2) + "\n", encoding="utf-8",
    )
    for case in cases:
        print(json.dumps({
            key: case[key] for key in (
                "scenario", "reads", "baseline_n50", "branch_physical_nodes",
                "possible_transitions", "transitions_with_1_molecule",
                "transitions_with_2_molecules", "uniquely_resolved_transitions",
                "projection_only_n50",
            )
        }), flush=True)


if __name__ == "__main__":
    main()
